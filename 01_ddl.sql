-- =====================================================================
-- 01_ddl.sql  |  Sistema de Matrícula Acadêmica  |  PostgreSQL 17
-- Rascunho do DDL a partir do modelo lógico fornecido pelo professor.
--
-- Como ler: cada tabela segue a ordem "pai antes de filho"
-- (uma tabela só pode referenciar outra que já existe).
-- Regra geral das chaves estrangeiras: sem ON DELETE explícito, o
-- PostgreSQL NÃO deixa apagar um registro "pai" que ainda tem "filhos".
-- =====================================================================

-- ---------------------------------------------------------------------
-- 0) DOMÍNIOS E TIPOS
-- Um DOMÍNIO é um tipo com regra embutida: define a regra uma vez e
-- reutiliza em várias colunas.
-- ---------------------------------------------------------------------
CREATE DOMAIN d_cpf AS char(11)
    CHECK (VALUE ~ '^[0-9]{11}$');              -- exatamente 11 dígitos

CREATE DOMAIN d_nota AS numeric(3,1)
    CHECK (VALUE BETWEEN 0 AND 10);             -- nota de 0,0 a 10,0

CREATE DOMAIN d_percentual AS numeric(5,2)
    CHECK (VALUE BETWEEN 0 AND 100);            -- frequência de 0 a 100

-- O diagrama usa o tipo "vinculo_t" em tb_pre_requisito, mas não mostra
-- os valores.
CREATE TYPE vinculo_t AS ENUM ('PRE_REQUISITO', 'CO_REQUISITO');

-- ---------------------------------------------------------------------
-- 1) CAMPUS, CURSO, CURRÍCULO
-- ---------------------------------------------------------------------
CREATE TABLE tb_campus (
    id_campus    int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_campus  varchar(60) NOT NULL UNIQUE,
    cidade       varchar(60) NOT NULL
);

CREATE TABLE tb_curso (
    id_curso      int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_campus     int NOT NULL REFERENCES tb_campus (id_campus),
    codigo_curso  varchar(10)  NOT NULL UNIQUE,
    nome_curso    varchar(120) NOT NULL,
    grau          varchar(20)  NOT NULL,
    ch_total      int NOT NULL CHECK (ch_total > 0)
);

CREATE TABLE tb_curriculo (
    id_curriculo  int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_curso      int NOT NULL REFERENCES tb_curso (id_curso),
    ano_vigencia  smallint NOT NULL CHECK (ano_vigencia BETWEEN 1990 AND 2100),
    ativo         boolean  NOT NULL DEFAULT true,
    UNIQUE (id_curso, ano_vigencia)             -- um currículo por curso/ano
);

-- ---------------------------------------------------------------------
-- 2) DISCIPLINA, CURRÍCULO x DISCIPLINA, PRÉ-REQUISITO
-- ---------------------------------------------------------------------
CREATE TABLE tb_disciplina (
    id_disciplina      int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_disciplina  varchar(10) NOT NULL UNIQUE,
    nome_disciplina    varchar(60) NOT NULL,
    ementa             text,
    ch_teorico         smallint NOT NULL DEFAULT 0 CHECK (ch_teorico >= 0),
    ch_pratico         smallint NOT NULL DEFAULT 0 CHECK (ch_pratico >= 0),
    -- COLUNA GERADA: o banco calcula sozinho e não aceita INSERT/UPDATE nela.
    ch_total           smallint GENERATED ALWAYS AS (ch_teorico + ch_pratico) STORED
);

-- Tabela de ligação N:N (um currículo tem várias disciplinas e vice-versa).
-- A chave primária composta impede repetir a mesma disciplina no currículo.
CREATE TABLE curriculo_disciplina (
    id_curriculo          int NOT NULL REFERENCES tb_curriculo (id_curriculo),
    id_disciplina         int NOT NULL REFERENCES tb_disciplina (id_disciplina),
    tipo_curso_disciplina varchar(60),
    periodo               smallint CHECK (periodo BETWEEN 1 AND 12),
    PRIMARY KEY (id_curriculo, id_disciplina)
);

-- Auto-relacionamento N:N em disciplina: "id_disciplina exige id_requisito".
CREATE TABLE tb_pre_requisito (
    id_disciplina  int NOT NULL REFERENCES tb_disciplina (id_disciplina),
    id_requisito   int NOT NULL REFERENCES tb_disciplina (id_disciplina),
    vinculo        vinculo_t NOT NULL DEFAULT 'PRE_REQUISITO',
    PRIMARY KEY (id_disciplina, id_requisito),
    CHECK (id_disciplina <> id_requisito)       -- disciplina não é pré-requisito dela mesma
);
-- Obs.: um CHECK não impede ciclos longos (A exige B, B exige A).
-- Isso exigiria um trigger com consulta recursiva (bom ponto para defesa).

-- ---------------------------------------------------------------------
-- 3) PERÍODO LETIVO, FERIADO, PROFESSOR, SALA
-- ---------------------------------------------------------------------
CREATE TABLE tb_periodo_letivo (
    id_periodo_letivo   int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ano_periodo_letivo  smallint NOT NULL,
    semestre            smallint NOT NULL CHECK (semestre IN (1, 2)),
    data_inicio         date NOT NULL,
    data_fim            date NOT NULL,
    CHECK (data_fim > data_inicio),
    UNIQUE (ano_periodo_letivo, semestre)
);

CREATE TABLE tb_feriado (
    id_feriado         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_campus          int NOT NULL REFERENCES tb_campus (id_campus),
    descricao_feriado  varchar(120) NOT NULL,
    data_feriado       date NOT NULL,
    UNIQUE (id_campus, data_feriado)
);

CREATE TABLE tb_professor (
    id_professor         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula_professor  varchar(12)  NOT NULL UNIQUE,
    nome_professor       varchar(100) NOT NULL,
    email                varchar(120) NOT NULL UNIQUE,
    titulacao            varchar(20)
);

CREATE TABLE sala (
    id_sala      int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_campus    int NOT NULL REFERENCES tb_campus (id_campus),
    tipo_sala    varchar(60),
    codigo_sala  varchar(10) NOT NULL,
    capacidade   smallint NOT NULL CHECK (capacidade > 0),
    UNIQUE (id_campus, codigo_sala)             -- código da sala é único dentro do campus
);

-- ---------------------------------------------------------------------
-- 4) TURMA E HORÁRIOS
-- ---------------------------------------------------------------------
CREATE TABLE tb_turma (
    id_turma           int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_periodo_letivo  int NOT NULL REFERENCES tb_periodo_letivo (id_periodo_letivo),
    id_professor       int NOT NULL REFERENCES tb_professor (id_professor),
    id_disciplina      int NOT NULL REFERENCES tb_disciplina (id_disciplina),
    codigo_turma       int NOT NULL,
    turno_turma        varchar(10) NOT NULL,
    vagas_turma        smallint NOT NULL CHECK (vagas_turma >= 0),
    UNIQUE (id_periodo_letivo, id_disciplina, codigo_turma)
);

CREATE TABLE tb_turma_horario (
    id_turma_horario     int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_turma             int NOT NULL REFERENCES tb_turma (id_turma),
    id_sala              int NOT NULL REFERENCES sala (id_sala),
    dia_semana           smallint NOT NULL CHECK (dia_semana BETWEEN 1 AND 7),
    inicio_turma_horario time NOT NULL,
    fim_turma_horario    time NOT NULL,
    CHECK (fim_turma_horario > inicio_turma_horario)
);

-- ---------------------------------------------------------------------
-- 5) ALUNO, MATRÍCULA, HISTÓRICO, LOG
-- ---------------------------------------------------------------------
CREATE TABLE tb_aluno (
    id_aluno         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_curso         int NOT NULL REFERENCES tb_curso (id_curso),
    id_curriculo     int NOT NULL REFERENCES tb_curriculo (id_curriculo),
    nome_aluno       varchar(120) NOT NULL,
    cpf_aluno        d_cpf NOT NULL UNIQUE,
    matricula_aluno  int NOT NULL UNIQUE,
    nascimento_aluno date NOT NULL,
    ingresso_aluno   date NOT NULL,
    status_aluno     boolean NOT NULL DEFAULT true,
    CHECK (ingresso_aluno > nascimento_aluno)
);

CREATE TABLE tb_matricula (
    id_matricula      int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_turma          int NOT NULL REFERENCES tb_turma (id_turma),
    id_aluno          int NOT NULL REFERENCES tb_aluno (id_aluno),
    data_matricula    date NOT NULL DEFAULT current_date,
    status_matricula  boolean NOT NULL DEFAULT true,
    UNIQUE (id_turma, id_aluno)                 -- aluno não se matricula 2x na mesma turma
);

-- Relação 1:1 com matrícula (id_matricula é FK e UNIQUE ao mesmo tempo).
CREATE TABLE tb_historico (
    id_historico  int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_matricula  int NOT NULL UNIQUE REFERENCES tb_matricula (id_matricula),
    nota_a1       d_nota,
    nota_a2       d_nota,
    frequencia    d_percentual,
    situacao      boolean,
    media_final   d_nota
);

CREATE TABLE tb_log_matricula (
    id_log_matricula  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula_id      int NOT NULL REFERENCES tb_matricula (id_matricula),
    acao_log          varchar(20) NOT NULL,
    detalhe_log       text,
    usuario_log       varchar(100) NOT NULL DEFAULT current_user,
    ocorrido_em       date NOT NULL DEFAULT current_date   -- no diagrama é date; timestamp seria melhor
);
